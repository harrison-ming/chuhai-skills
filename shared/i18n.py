def norm_lang(lang):
    """Return a supported language code; None means the default (zh)."""
    if lang is None:
        return DEFAULT_LANG
    code = str(lang).strip().lower().replace("_", "-")
    if code.startswith("zh"):
        return "zh"
    if code.startswith("en"):
        return "en"
    raise ValueError("unsupported lang %r (use zh or en)" % lang)


def text(key, lang=None):
    return TEXT[norm_lang(lang)][key]
