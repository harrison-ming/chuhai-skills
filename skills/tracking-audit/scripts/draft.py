def appendix(summary, lang):
    T = TXT[lang]
    out = [T["appendix"], ""]
    out.append(T["status"] % summary.get("status"))
    out.append(T["warnings"] % (", ".join(summary.get("warnings") or []) or "-"))
    df = summary.get("data_files") or []
    if df:
        out.append(T["rules"] % "; ".join(d.get("note", "") for d in df))
    out.append("")
    out.append(T["pages_h"])
    out.append("")
    out.append(T["pages_t"])
    for p in summary.get("pages") or []:
        out.append(
            "| %s | %s | %s | %s |"
            % (
                T["page_names"].get(p["key"], p["key"]),
                esc(p.get("url") or "-"),
                esc(p.get("result")),
                esc(p.get("http_status") or "-"),
            )
        )
    for c in summary.get("containers") or []:
        out.append("| %s | %s | ok | - |" % (c["id"], "googletagmanager.com"))
    out.append("")
    out.append(T["ids_h"])
    out.append("")
    out.append(T["ids_t"])
    for t in summary.get("tags") or []:
        vias = ", ".join(cat.pick(cat.VIA[v], lang) for v in t["install_via"])
        out.append(
            "| %s | %s | %s | %s | %s |"
            % (
                cat.pick(cat.PLATFORM.get(t["platform"], (t["platform"],) * 2), lang),
                esc(t["id"] or "-"),
                esc(vias),
                evidence.label(t["badge_key"], lang),
                esc(", ".join(t["sources"])),
            )
        )
    probs = summary.get("problems") or []
    ua = summary.get("legacy_ua") or []
    if probs or ua:
        out.append("")
        out.append(T["prob_h"])
        out.append("")
        for h in probs:
            out.append(
                "- %s: `%s` (%s, %s)"
                % (h["platform"], esc(h["id"]), h["problem"], h["source"])
            )
        for u in ua:
            out.append("- UA: `%s`" % esc(u))
    inv = (summary.get("web_pixels") or {}).get("inventory") or []
    inv = [i for i in inv if i.get("platform") != "shopify"]
    if inv:
        out.append("")
        out.append(T["inv_h"])
        out.append("")
        out.append(T["inv_t"])
        for i in inv[:60]:
            kind = T["app"] if i["type"] == "APP" else T["custom"]
            out.append(
                "| %s | %s | %s | %s |"
                % (
                    kind,
                    esc(i.get("name") or i.get("app") or "-"),
                    esc(i.get("sandbox") or "-"),
                    esc(i.get("platform") or "-"),
                )
            )
    out.append("")
    out.append(T["ev_h"])
    out.append("")
    out.append(T["levels"])
    out.append("")
    out.append(T["ev_t"])
    for i, r in enumerate(summary.get("checks") or [], 1):
        level = {
            "verified": "E1",
            "on_page": "E1",
            "self_claim": "E2",
            "inferred": "E6",
        }.get(r["badge_key"], "-")
        if r.get("source_kind") == "user" or (
            r["badge_key"] == "verified" and r.get("needs_user")
        ):
            level = "E1"
        out.append(
            "| E%03d | %s | %s | %s | %s | %s |"
            % (
                i,
                level,
                r["id"],
                esc(r["platform_label"]),
                evidence.label(r["badge_key"], lang) if r["badge_key"] else "-",
                esc(r["evidence"] or "-"),
            )
        )
    return out


