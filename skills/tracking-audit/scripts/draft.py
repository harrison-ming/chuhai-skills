def esc(text):
    return str(text if text is not None else "").replace("|", "/").replace("\n", " ")


def row_line(r, lang):
    """One body bullet for a check row: item, result, badge, basis."""
    item = r["item"]
    if (
        r.get("platform") not in ("all", "shopify", None)
        and r["id"] not in cat.T_PLATFORM
        and r["id"] not in ("T03", "C01")
        and r.get("platform_label") not in item
    ):
        item = "%s (%s)" % (item, r["platform_label"])
    result = cat.pick(cat.RESULT[r["result"]], lang)
    if r["id"] in cat.T_PLATFORM and r["result"] == "pass":
        result = {"zh": "页面里有代码", "en": "code is on the page"}[lang]
    parts = ["- %s: %s" % (item, result)]
    if r.get("badge"):
        parts.append(r["badge"])
    basis = r.get("basis") or ""
    if r["id"] == "T03":
        basis = basis.split(";")[0]
    if basis:
        parts.append(basis if basis.endswith(".") else basis + ".")
    return " ".join(parts)


def render(summary):
    lang = summary.get("lang") or "zh"
    T = TXT[lang]
    rows = summary.get("checks") or []
    tags = summary.get("tags") or []
    out = []
    domain = summary.get("domain") or "site"
    other = summary.get("mode") == "other"
    out.append((T["title_other"] if other else T["title_own"]) % domain)
    out.append("")
    date = (summary.get("captured_at_utc") or "")[
        :10
    ] or datetime.date.today().isoformat()
    n_pages = len([p for p in summary.get("pages") or [] if p.get("file")])
    out.append(
        T["sub"]
        % (
            summary.get("base_url") or domain,
            date,
            n_pages,
            len(summary.get("containers") or []),
        )
    )
    out.append("")
    if summary.get("status") == "failed":
        return "\n".join(out + [T["glance"]] + failed_tail(summary, lang))
    # ---- at a glance
    out.append(T["glance"])
    out.append("")
    no_pages = "pages_not_checked" in (summary.get("warnings") or [])
    if no_pages:
        out.append("- %s %s" % (T["no_pages"], evidence.badge("not_found", lang)))
    seen = [p for p in PLATFORM_ROWS if any(t["platform"] == p for t in tags)]
    on_page = [
        p for p in seen if any(t["platform"] == p and t["calibrated"] for t in tags)
    ]
    guess = [p for p in seen if p not in on_page]
    if on_page:
        out.append(
            "- %s %s"
            % (
                T["seen"] % ", ".join(cat.pick(cat.PLATFORM[p], lang) for p in on_page),
                evidence.badge("on_page", lang),
            )
        )
    if guess:
        b = {
            "zh": "依据: 识别规则还没在足够多的真实店铺上校准",
            "en": "Basis: signature not yet calibrated on enough stores",
        }[lang]
        out.append(
            "- %s %s %s."
            % (
                T["seen"] % ", ".join(cat.pick(cat.PLATFORM[p], lang) for p in guess),
                evidence.badge("inferred", lang),
                b,
            )
        )
    if not seen:
        out.append("- %s %s" % (T["seen_none"], evidence.badge("not_found", lang)))
    issues = [r for r in rows if r["result"] == "issue"]
    high = [r for r in issues if r["severity"] == "high"]
    med = [r for r in issues if r["severity"] == "medium"]
    if high or med:
        out.append("- " + T["issues"] % (len(high), len(med)))
    else:
        out.append("- %s %s" % (T["issues_none"], evidence.badge("on_page", lang)))
    out.append("- %s %s" % (T["checkout"], evidence.badge("not_found", lang)))
    ident = (summary.get("identity") or {}).get("status")
    if ident == "not_shopify":
        b = {
            "zh": "依据: 首页里没有 Shopify 特征",
            "en": "Basis: no Shopify markers on the homepage",
        }[lang]
        out.append(
            "- %s %s %s." % (T["not_shopify"], evidence.badge("inferred", lang), b)
        )
    if other:
        out.append("- %s %s" % (T["other_note"], evidence.badge("not_found", lang)))
    out.append("")
    ev = summary.get("observed_events") or {}
    table_platforms = [
        p
        for p in PLATFORM_ROWS
        if p in seen or p in (summary.get("ad_platforms_said") or [])
    ]
    if table_platforms:
        out.append(T["table_head"])
        c01 = dict((r["platform"], r) for r in rows if r["id"] == "C01")
        for p in table_platforms:
            has = p in seen
            code = (
                "%s %s"
                % (
                    T["code_yes"],
                    evidence.badge("on_page" if p in on_page else "inferred", lang),
                )
                if has
                else "%s %s" % (T["code_no"], evidence.badge("not_found", lang))
            )
            if has and p not in on_page:
                code += (
                    " "
                    + {"zh": "依据: 规则未校准", "en": "Basis: uncalibrated signature"}[
                        lang
                    ]
                )
            browse = ev.get(p, {}).get("text") or "%s %s" % (
                T["browse_need"],
                evidence.badge("not_found", lang),
            )
            pr = c01.get(p)
            if pr and pr["result"] != "needs_input":
                purchase = "%s %s" % (pr["result_label"], pr["badge"])
                if pr["badge_key"] == "inferred":
                    purchase += " " + pr["basis"]
            else:
                purchase = "%s %s" % (
                    T["purchase_other"] if other else T["purchase_need"],
                    evidence.badge("not_found", lang),
                )
            out.append(
                "| %s | %s | %s | %s |"
                % (cat.pick(cat.PLATFORM[p], lang), code, esc(browse), purchase)
            )
        out.append("")
    out.append(T["top3"])
    tops = sorted(issues, key=lambda r: cat.SEVERITY_ORDER[r["severity"]])
    lines = []
    for r in tops:
        if r["severity"] == "info":
            continue
        text = "%s: %s" % (r["item"], r["fix"])
        if text not in lines:
            lines.append(text)
    if len(lines) < 3 and not other:
        lines.append(T["top_default"])
    for i, text in enumerate(lines[:3], 1):
        out.append("%d. %s" % (i, text))
    out.append("")
    out.append(T["cannot_see"])
    out.append("")
    if summary.get("status") == "failed":
        return "\n".join(out + failed_tail(summary, lang))
    # ---- platforms
    out.append(T["platforms"])
    out.append("")
    glossed = set()
    not_seen = []
    for r in rows:
        if (
            r["id"] not in cat.T_PLATFORM
            and not r["id"].startswith("E")
            and r["id"]
            not in (
                "T03",
                "T09",
                "T10",
                "T11",
            )
        ):
            continue
        if r["result"] == "not_seen" and r["id"] in cat.T_PLATFORM:
            not_seen.append(r)
            continue
        if r["result"] == "na":
            continue
        p = r["platform"]
        if p in cat.GLOSS and p not in glossed:
            glossed.add(p)
            r = dict(r, item=cat.pick(cat.GLOSS[p], lang))
        out.append(row_line(r, lang))
    if not_seen:
        names = ", ".join(r["platform_label"] for r in not_seen)
        out.append(
            "- %s %s" % (T["not_seen_line"] % names, evidence.badge("not_found", lang))
        )
    out.append("")
    # ---- duplicates
    out.append(T["dups"])
    out.append("")
    for r in rows:
        if r["id"] in ("D01", "D02", "D03", "D04", "D06"):
            out.append(row_line(r, lang))
    out.append("")
    # ---- checkout
    out.append(T["checkout_h"])
    out.append("")
    if (summary.get("identity") or {}).get("status") in ("confirmed", "probable"):
        for line in T["checkout_fixed"]:
            out.append("- " + line)
        out.append("- " + T["checkout_infer"])
        out.append("")
    for r in rows:
        if r["id"] in ("D05", "C01", "C02"):
            out.append(row_line(r, lang))
    out.append("")
    if other:
        out.append(T["ask_none"])
    else:
        ui = summary.get("user_inputs") or {}
        asked = list(ui.get("needed") or []) + [
            u for u in ui.get("answered") or [] if u not in (ui.get("needed") or [])
        ]
        if asked:
            out.append(T["ask_head"])
            for uid in sorted(asked):
                spec = cat.USER_INPUTS.get(uid)
                if not spec:
                    continue
                state = (
                    T["ask_done"]
                    if uid in (ui.get("answered") or [])
                    else T["ask_todo"]
                )
                out.append(
                    "| %s | %s | %s | %s |"
                    % (
                        uid,
                        esc(cat.pick(spec[:2], lang)),
                        esc(cat.pick(spec[2:], lang)),
                        state,
                    )
                )
            out.append("")
            out.append(T["ask_file"])
    out.append("")
    # ---- server
    out.append(T["server"])
    out.append("")
    out.append(T["server_note"])
    out.append("")
    for r in rows:
        if r["id"].startswith("S"):
            out.append(row_line(r, lang))
    out.append("")
    # ---- privacy
    out.append(T["privacy"])
    out.append("")
    out.append(T["privacy_fixed"])
    out.append("")
    for r in rows:
        if r["id"].startswith("P") and r["result"] != "na":
            out.append(row_line(r, lang))
    out.append("")
    # ---- fix list
    out.append(T["fix"])
    out.append("")
    fixes = [
        r
        for r in rows
        if r["result"] in ("issue", "not_seen", "needs_input")
        and r["severity"] in ("high", "medium", "low")
        and r["fix"] not in ("-", "")
    ]
    if not fixes:
        out.append(T["fix_none"])
    for sev in ("high", "medium", "low"):
        group = [r for r in fixes if r["severity"] == sev]
        if not group:
            continue
        out.append("**%s**" % cat.pick(cat.SEVERITY[sev], lang))
        out.append("")
        done = set()
        for r in group:
            key = (r["id"], r["platform"])
            if key in done:
                continue
            done.add(key)
            who = (
                T["who_app"]
                if r["id"] in WHO["app"]
                else T["who_dev"]
                if r["id"] in WHO["dev"]
                else T["who_check"]
            )
            out.append(
                "- %s (%s): %s %s" % (r["item"], r["platform_label"], r["fix"], who)
            )
        out.append("")
    # ---- open questions
    out.append(T["open"])
    out.append("")
    missing = [
        T["page_names"].get(p["key"], p["key"])
        for p in summary.get("pages") or []
        if not p.get("file")
    ]
    opens = []
    if missing:
        opens.append(
            T["open_page"] % ", ".join(missing)
            + " "
            + evidence.badge("not_found", lang)
        )
    conts = [
        w.split(":", 1)[1]
        for w in summary.get("warnings") or []
        if w.startswith("container_missing:")
    ]
    if conts:
        opens.append(
            T["open_cont"] % len(conts) + " " + evidence.badge("not_found", lang)
        )
    need = (summary.get("user_inputs") or {}).get("needed") or []
    if need and not other:
        opens.append(
            T["open_input"] % ", ".join(need) + " " + evidence.badge("not_found", lang)
        )
    for o in opens or [T["open_none"]]:
        out.append("- " + o)
    out.append("")
    if no_pages:
        out = drop_sections(out, (T["platforms"], T["dups"], T["privacy"]))
    out += appendix(summary, lang)
    out.append("")
    out.append(FIXED_ENDING[lang])
    return "\n".join(out)


def drop_sections(lines, headings):
    """Remove whole "## " sections whose heading is in ``headings``."""
    out, skip = [], False
    for line in lines:
        if line.startswith("## "):
            skip = line in headings
        if not skip:
            out.append(line)
    return out


